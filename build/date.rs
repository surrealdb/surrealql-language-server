//! The calendar date of a Unix timestamp, for `build.rs` to stamp the binary
//! with. Shared with `tests/cli.rs` through `#[path]`, because a build
//! script's own tests never run.

/// `seconds` since the Unix epoch as a UTC `YYYY-MM-DD`.
///
/// Howard Hinnant's `civil_from_days`, proleptic Gregorian, so no dependency
/// is needed for one date.
pub fn utc_date(seconds: i64) -> String {
    let days = seconds.div_euclid(86_400);
    let shifted = days + 719_468;
    let era = shifted.div_euclid(146_097);
    let day_of_era = shifted.rem_euclid(146_097);
    let year_of_era =
        (day_of_era - day_of_era / 1_460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let month_index = (5 * day_of_year + 2) / 153;
    let day = day_of_year - (153 * month_index + 2) / 5 + 1;
    let month = if month_index < 10 {
        month_index + 3
    } else {
        month_index - 9
    };
    let year = year_of_era + era * 400 + i64::from(month <= 2);
    format!("{year:04}-{month:02}-{day:02}")
}
